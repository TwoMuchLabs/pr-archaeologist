"""CODEBASE_ARCHAEOLOGY.md: the index an AI coding agent reads before touching a file.

Design rules for this file:
* Every file section has the exact heading "### `path`" so an agent can grep for it.
* Output is deterministic for a given HEAD (no wall-clock timestamps), so a nightly run
  with no new commits produces no diff.
* Fragile files come first; stable files collapse into one table to keep it readable.
"""

from __future__ import annotations

from typing import Dict, List

from .model import ranked

ICON = {"fragile": "🔴", "caution": "🟠", "stable": "🟢"}


def _esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _refs(event: Dict) -> str:
    bits = [f"#{n}" for n in event.get("prs", [])] + event.get("tickets", [])
    return f" ({', '.join(bits)})" if bits else ""


def _file_section(f: Dict, max_events: int) -> List[str]:
    out = [f"### `{f['path']}`", ""]
    risk = f"{ICON[f['level']]} **{f['level']}** (score {f['score']}/100)"
    if f.get("prose"):
        risk = "documentation, not scored"
    if f["reasons"]:
        risk += " — " + ", ".join(f["reasons"])
    out.append(f"- **Risk:** {risk}")
    out.append(
        f"- **History:** {f['commits']} commits, {f['first']} → {f['last']}, by {', '.join(f['authors']) or 'unknown'}"
        + (f" (+{f['author_count'] - len(f['authors'])} more)" if f["author_count"] > len(f["authors"]) else "")
    )
    if f["previous"]:
        out.append("- **Previously:** " + ", ".join(f"`{p}`" for p in f["previous"]))
    if f["intent"]:
        out.append("- **Why it exists:**")
        for item in f["intent"]:
            line = f"  - {item['date']} `{item['ref']}` {item['text']} — {item['author']}"
            out.append(line)
            for why in item["why"]:
                out.append(f"    - {why}")
    if f["docs"]:
        out.append("- **Decisions and docs:**")
        for doc in f["docs"]:
            status = f" _{doc['status']}_" if doc.get("status") else ""
            out.append(f"  - [{doc['label']}: {doc['title']}]({doc['path']}){status}")
            if doc.get("decision"):
                out.append(f"    - Decision: {doc['decision']}")
    if f["pitfalls"]:
        out.append("- **Past pitfalls (read before editing):**")
        for pit in f["pitfalls"][-max_events:]:
            where = " ".join(x for x in (pit["date"], f"`{pit['ref']}`" if pit["ref"] else "") if x)
            out.append(f"  - [{pit['kind']}] {where + ' ' if where else ''}{pit['text']}")
    if f["coupled"]:
        out.append("- **Usually changes with:** " + ", ".join(
            f"`{c['path']}` ({c['count']}/{c['of']})" for c in f["coupled"]))
    risky_syms = [s for s in f["symbols"] if s["fixes"] and not s["container"]]
    if risky_syms:
        out.append("- **Functions with a history:**")
        for sym in risky_syms[:12]:
            fixes = "; ".join(f"{e['date']} `{e['short']}` {e['title']}" for e in sym["fixes"][-3:])
            out.append(f"  - `{sym['name']}` (L{sym['start']}–{sym['end']}): {fixes}")
    out.append("")
    return out


def render(report: Dict, max_sections: int = 300, max_events: int = 14) -> str:
    meta = report["meta"]
    files = ranked(report)
    notable = [f for f in files if f["level"] != "stable" or f["fixes"] or f["docs"] or f["reverts"]]
    quiet = [f for f in files if f not in notable]
    out: List[str] = []
    out += [
        f"# Codebase Archaeology — {meta['repo']}",
        "",
        f"> Generated by pr-archaeologist from {meta['commits']} commits "
        f"({meta['first_commit']} → {meta['head_date']}), up to `{(meta['head'] or '')[:7]}`. "
        "Do not edit by hand: it is regenerated nightly.",
        "",
        "## How to use this file (for AI coding agents)",
        "",
        "1. **Before editing a file, find its section**: search for the heading `### \\`<path>\\``.",
        "2. Read **Past pitfalls** and **Why it exists**. If your change would undo a recorded fix or "
        "contradict a decision record, stop and say so instead of proceeding silently.",
        "3. If the file lists **Usually changes with**, open those files too: they tend to break together.",
        "4. For more detail run `pr-archaeologist explain <path>` (add `--json` for structured output, "
        "`--function NAME` for one function).",
        "5. Files not listed under *Files with history worth knowing* are in the *Quiet files* table: "
        "no recorded fixes, reverts or decisions.",
        "",
        "Scores are heuristics computed from commit messages, blame and co-change, not ground truth. "
        f"🔴 fragile ≥ {meta['thresholds']['fragile']}, 🟠 caution ≥ {meta['thresholds']['caution']}, 🟢 stable below that.",
        "",
    ]
    if meta["truncated"]:
        out += ["> Note: history was truncated with `--max-commits`; origins may be later than shown.", ""]

    hot = [f for f in files if f["level"] != "stable"][:40]
    out += ["## Fragile files at a glance", ""]
    if hot:
        out += ["| File | Risk | Score | Fixes | Reverts | Commits | Why it is risky |", "|---|---|---:|---:|---:|---:|---|"]
        for f in hot:
            out.append(
                f"| `{f['path']}` | {ICON[f['level']]} {f['level']} | {f['score']} | {f['fixes']} | "
                f"{f['reverts']} | {f['commits']} | {_esc(', '.join(f['reasons']))} |"
            )
    else:
        out.append("No file crosses the caution threshold yet.")
    out.append("")

    adrs = [d for d in report["docs"].values() if d["kind"] == "adr"]
    if adrs:
        out += ["## Decision records", ""]
        for doc in sorted(adrs, key=lambda d: d["path"]):
            status = f" — _{doc['status']}_" if doc.get("status") else ""
            date = f" ({doc['date']})" if doc.get("date") else ""
            out.append(f"- **[{doc['label']}: {doc['title']}]({doc['path']})**{status}{date}")
            if doc.get("decision"):
                out.append(f"  - Decision: {doc['decision']}")
            if doc.get("consequences"):
                out.append(f"  - Consequences: {doc['consequences']}")
            if doc["files"]:
                out.append("  - Governs: " + ", ".join(f"`{p}`" for p in doc["files"][:12]))
        out.append("")

    pairs = {}
    for f in files:
        for link in f["coupled"]:
            if link["strong"]:
                key = tuple(sorted((f["path"], link["path"])))
                pairs[key] = max(pairs.get(key, 0), link["count"])
    if pairs:
        out += ["## Hidden couplings", "", "Files that history says change together, whatever the import graph says.", ""]
        for (a, b), n in sorted(pairs.items(), key=lambda kv: (-kv[1], kv[0]))[:40]:
            out.append(f"- `{a}` ↔ `{b}` — changed together in {n} commits")
        out.append("")

    out += ["## Files with history worth knowing", ""]
    for f in notable[:max_sections]:
        out += _file_section(f, max_events)
    if len(notable) > max_sections:
        out += [f"_{len(notable) - max_sections} more files omitted; use `pr-archaeologist explain <path>`._", ""]

    if quiet:
        out += ["## Quiet files", "", "| File | Born | Commits | Original purpose |", "|---|---|---:|---|"]
        for f in sorted(quiet, key=lambda f: f["path"])[:1500]:
            purpose = f["intent"][0]["text"] if f["intent"] else ""
            out.append(f"| `{f['path']}` | {f['first']} | {f['commits']} | {_esc(purpose)} |")
        out.append("")

    dead = [f for f in report["files"].values() if f["status"] == "deleted" and f["deleted"]]
    if dead:
        out += ["## Graveyard", "", "Deleted files and why they went. Check here before re-creating one.", ""]
        for f in sorted(dead, key=lambda f: f["deleted"]["date"], reverse=True)[:100]:
            gone = f["deleted"]
            why = f" — {gone['why'][0]}" if gone["why"] else ""
            out.append(f"- `{f['path']}` removed {gone['date']} `{gone['short']}`: {gone['title']}{why}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"
